import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { initStore, getDashboard, createEndpoint, findEndpoint, deleteEndpoint, clearEndpointRequests, addRequest, findRequest } from './store.js';
import { sanitizeHeaders, validatePublicHttpUrl } from './security.js';

const app = express();
const PORT = Number(process.env.PORT) || 4000;
const ORIGINS = (process.env.CLIENT_ORIGIN || 'http://localhost:5173').split(',').map(v => v.trim());
const LIMIT = '1mb';
app.disable('x-powered-by');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors({ origin: ORIGINS, methods: ['GET','POST','DELETE','OPTIONS'], allowedHeaders: ['Content-Type'] }));
app.use(express.json({ limit: LIMIT, type: ['application/json','application/*+json'] }));
app.use(express.text({ limit: LIMIT, type: ['text/*','application/xml'] }));
app.use(express.urlencoded({ extended: false, limit: LIMIT }));

const eventName = body => body && typeof body === 'object' && !Array.isArray(body) ? String(body.event || body.type || body.event_type || '').slice(0,120) : '';
const bodyText = body => body == null ? '' : typeof body === 'string' ? body : JSON.stringify(body);
function safeBody(body) {
  if (body === undefined || body === '') return null;
  const text = bodyText(body);
  return Buffer.byteLength(text) > 1024 * 1024 ? '[Body omitted: too large]' : body;
}
app.get('/api/health', (_req,res) => res.json({ ok:true, service:'HookLab API', timestamp:new Date().toISOString() }));
app.get('/api/dashboard', (_req,res) => res.json(getDashboard()));
app.post('/api/endpoints', async (req,res,next) => {
  try {
    const name = typeof req.body?.name === 'string' ? req.body.name.trim() : '';
    if (!name) return res.status(400).json({ error:'Endpoint name is required.' });
    if (name.length > 60) return res.status(400).json({ error:'Endpoint name must be 60 characters or fewer.' });
    res.status(201).json({ endpoint: await createEndpoint(name) });
  } catch(e) { next(e); }
});
app.delete('/api/endpoints/:id', async (req,res,next) => {
  try { if (!findEndpoint(req.params.id)) return res.status(404).json({error:'Endpoint not found.'}); await deleteEndpoint(req.params.id); res.json({ok:true}); }
  catch(e) { next(e); }
});
app.delete('/api/endpoints/:id/requests', async (req,res,next) => {
  try { if (!findEndpoint(req.params.id)) return res.status(404).json({error:'Endpoint not found.'}); await clearEndpointRequests(req.params.id); res.json({ok:true}); }
  catch(e) { next(e); }
});
app.post('/api/endpoints/:id/sample', async (req,res,next) => {
  try {
    const endpoint = findEndpoint(req.params.id);
    if (!endpoint) return res.status(404).json({error:'Endpoint not found.'});
    const body = { event:'payment.success', test:true, id:`evt_test_${Date.now()}`, created_at:new Date().toISOString(), data:{message:'Sample event generated by HookLab.'} };
    const saved = await addRequest({ endpointId:endpoint.id, method:'POST', path:`/hooks/${endpoint.id}`, query:{}, headers:{'content-type':'application/json','x-hooklab-sample':'true'}, body, bodyText:JSON.stringify(body), receivedAt:new Date().toISOString(), sourceIp:'127.0.0.1', contentLength:Buffer.byteLength(JSON.stringify(body)), eventName:eventName(body) });
    res.status(201).json({request:saved});
  } catch(e) { next(e); }
});
app.post('/api/requests/:id/replay', async (req,res,next) => {
  try {
    const saved = findRequest(req.params.id);
    if (!saved) return res.status(404).json({error:'Captured request not found.'});
    const destination = typeof req.body?.destinationUrl === 'string' ? req.body.destinationUrl.trim() : '';
    if (!destination) return res.status(400).json({error:'Destination URL is required.'});
    const url = await validatePublicHttpUrl(destination);
    const method = ['GET','POST','PUT','PATCH','DELETE'].includes(saved.method) ? saved.method : 'POST';
    const headers = {};
    for (const [k,v] of Object.entries(saved.headers || {})) if (['content-type','accept','x-webhook-event'].includes(k.toLowerCase()) && typeof v === 'string') headers[k] = v;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 8000);
    let response;
    try { response = await fetch(url, { method, headers, body:['GET','HEAD'].includes(method) || saved.body == null ? undefined : bodyText(saved.body), signal:controller.signal, redirect:'error' }); }
    finally { clearTimeout(timeout); }
    res.json({ok:response.ok,status:response.status,statusText:response.statusText,responseBody:(await response.text().catch(()=>'' )).slice(0,2000)});
  } catch(e) {
    if (e.name === 'AbortError') return res.status(504).json({error:'Replay timed out after 8 seconds.'});
    if (/blocked|valid destination|resolve/.test(e.message || '')) return res.status(400).json({error:e.message});
    next(e);
  }
});
app.all('/hooks/:id', async (req,res,next) => {
  try {
    const endpoint = findEndpoint(req.params.id);
    if (!endpoint) return res.status(404).json({error:'Webhook endpoint not found.'});
    const body = safeBody(req.body);
    const raw = bodyText(body);
    const saved = await addRequest({
      endpointId:endpoint.id, method:req.method, path:req.path,
      query:Object.fromEntries(Object.entries(req.query).map(([k,v]) => [k,Array.isArray(v) ? v.map(String) : String(v)])),
      headers:sanitizeHeaders(req.headers), body, bodyText:raw.slice(0,1024*1024),
      receivedAt:new Date().toISOString(), sourceIp:String(req.ip || req.socket.remoteAddress || 'unknown').replace(/^::ffff:/,''),
      contentLength:Number(req.headers['content-length']) || Buffer.byteLength(raw), eventName:eventName(body)
    });
    res.status(200).json({ok:true,received:true,requestId:saved.id,message:'Webhook captured by HookLab.'});
  } catch(e) { next(e); }
});
app.use((_req,res) => res.status(404).json({error:'Route not found.'}));
app.use((err,_req,res,_next) => {
  console.error('[HookLab]',err.message);
  if (err.type === 'entity.too.large') return res.status(413).json({error:'Request body exceeds the 1 MB limit.'});
  if (err instanceof SyntaxError && 'body' in err) return res.status(400).json({error:'Invalid JSON body.'});
  res.status(500).json({error:'An unexpected server error occurred.'});
});
await initStore();
app.listen(PORT,'0.0.0.0',() => console.log(`HookLab API listening on http://localhost:${PORT}`));
